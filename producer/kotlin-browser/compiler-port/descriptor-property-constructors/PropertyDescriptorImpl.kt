package org.jetbrains.kotlin.descriptors.impl

import org.jetbrains.kotlin.descriptors.*
import org.jetbrains.kotlin.descriptors.CallableDescriptor.UserDataKey
import org.jetbrains.kotlin.descriptors.CallableMemberDescriptor.Kind
import org.jetbrains.kotlin.descriptors.annotations.Annotations
import org.jetbrains.kotlin.name.Name
import org.jetbrains.kotlin.resolve.scopes.receivers.ContextReceiver
import org.jetbrains.kotlin.resolve.scopes.receivers.ExtensionReceiver
import org.jetbrains.kotlin.resolve.scopes.receivers.ImplicitContextReceiver
import org.jetbrains.kotlin.resolve.descriptorUtil.builtIns
import org.jetbrains.kotlin.types.*
import org.jetbrains.kotlin.utils.SmartSet

open class PropertyDescriptorImpl protected constructor(
    containingDeclaration: DeclarationDescriptor, original: PropertyDescriptor?, annotations: Annotations,
    private val modality: Modality, private var visibility: DescriptorVisibility, isVar: Boolean, name: Name,
    private val kind: Kind, source: SourceElement, private val lateInit: Boolean, private val isConst: Boolean,
    private val isExpect: Boolean, private val isActual: Boolean, private val isExternal: Boolean, private val delegated: Boolean,
) : VariableDescriptorWithInitializerImpl(containingDeclaration, annotations, name, null, isVar, source), PropertyDescriptor {
    private var overriddenProperties: Collection<PropertyDescriptor?>? = null
    private val original: PropertyDescriptor = original ?: this
    private var contextReceiverParameters: List<ReceiverParameterDescriptor> = emptyList()
    private var dispatchReceiverParameter: ReceiverParameterDescriptor? = null
    private var extensionReceiverParameter: ReceiverParameterDescriptor? = null
    private var typeParameters: List<TypeParameterDescriptor>? = null
    private var storedGetter: PropertyGetterDescriptorImpl? = null
    private var storedSetter: PropertySetterDescriptor? = null
    private var setterProjectedOut = false
    private var backingField: FieldDescriptor? = null
    private var delegateField: FieldDescriptor? = null

    open fun setInType(inType: KotlinType) { /* The corresponding setter is generated by default. */ }
    override fun getInType(): KotlinType? = storedSetter?.getValueParameters()?.get(0)?.getType()
    @Deprecated("This method is left for binary compatibility with android.nav.safearg plugin. Used in SafeArgSyntheticDescriptorGenerator.kt")
    open fun setType(outType: KotlinType, typeParameters: List<TypeParameterDescriptor>, dispatchReceiverParameter: ReceiverParameterDescriptor?,
        extensionReceiverParameter: ReceiverParameterDescriptor?) = setType(outType, typeParameters, dispatchReceiverParameter, extensionReceiverParameter, emptyList())
    open fun setType(outType: KotlinType, typeParameters: List<TypeParameterDescriptor>, dispatchReceiverParameter: ReceiverParameterDescriptor?,
        extensionReceiverParameter: ReceiverParameterDescriptor?, contextReceiverParameters: List<ReceiverParameterDescriptor>) {
        setOutType(outType)
        this.typeParameters = ArrayList(typeParameters)
        this.extensionReceiverParameter = extensionReceiverParameter
        this.dispatchReceiverParameter = dispatchReceiverParameter
        this.contextReceiverParameters = contextReceiverParameters
    }
    open fun initialize(getter: PropertyGetterDescriptorImpl?, setter: PropertySetterDescriptor?) = initialize(getter, setter, null, null)
    open fun initialize(getter: PropertyGetterDescriptorImpl?, setter: PropertySetterDescriptor?, backingField: FieldDescriptor?, delegateField: FieldDescriptor?) {
        storedGetter = getter; storedSetter = setter; this.backingField = backingField; this.delegateField = delegateField
    }
    open fun setSetterProjectedOut(value: Boolean) { setterProjectedOut = value }
    open fun setVisibility(visibility: DescriptorVisibility) { this.visibility = visibility }
    override fun getTypeParameters(): List<TypeParameterDescriptor> = typeParameters ?: throw IllegalStateException("typeParameters == null for $this")
    override fun validate() { getTypeParameters() }
    override fun getContextReceiverParameters(): List<ReceiverParameterDescriptor> = contextReceiverParameters
    override fun getExtensionReceiverParameter(): ReceiverParameterDescriptor? = extensionReceiverParameter
    override fun getDispatchReceiverParameter(): ReceiverParameterDescriptor? = dispatchReceiverParameter
    override fun getReturnType(): KotlinType = getType()
    override fun getModality(): Modality = modality
    override fun getVisibility(): DescriptorVisibility = visibility
    override val getter: PropertyGetterDescriptorImpl? get() = storedGetter
    override val setter: PropertySetterDescriptor? get() = storedSetter
    override fun isSetterProjectedOut(): Boolean = setterProjectedOut
    override fun isLateInit(): Boolean = lateInit
    override fun isConst(): Boolean = isConst
    override fun isExternal(): Boolean = isExternal
    override val isDelegated: Boolean get() = delegated
    override fun getAccessors(): List<PropertyAccessorDescriptor> {
        val result = ArrayList<PropertyAccessorDescriptor>(2)
        storedGetter?.let { result.add(it) }; storedSetter?.let { result.add(it) }
        return result
    }
    override fun substitute(originalSubstitutor: TypeSubstitutor): PropertyDescriptor? {
        if (originalSubstitutor.isEmpty()) return this
        return newCopyBuilder().setSubstitution(originalSubstitutor.getSubstitution()).setOriginal(getOriginal()).build()
    }
    open inner class CopyConfiguration : CallableMemberDescriptor.CopyBuilder<PropertyDescriptor?> {
        internal var owner: DeclarationDescriptor = getContainingDeclaration()
        internal var modality: Modality = getModality()
        internal var visibility: DescriptorVisibility = getVisibility()
        internal var original: PropertyDescriptor? = null
        internal var preserveSourceElement = false
        internal var kind: Kind = getKind()
        internal var substitution: TypeSubstitution = TypeSubstitution.EMPTY
        internal var copyOverrides = true
        internal var dispatchReceiverParameter: ReceiverParameterDescriptor? = this@PropertyDescriptorImpl.dispatchReceiverParameter
        internal var newTypeParameters: List<TypeParameterDescriptor>? = null
        internal var name: Name = getName()
        internal var returnType: KotlinType = getType()
        override fun setOwner(owner: DeclarationDescriptor): CopyConfiguration { this.owner = owner; return this }
        override fun setOriginal(original: CallableMemberDescriptor?): CopyConfiguration { this.original = original as PropertyDescriptor?; return this }
        override fun setPreserveSourceElement(): CopyConfiguration { preserveSourceElement = true; return this }
        override fun setReturnType(type: KotlinType): CallableMemberDescriptor.CopyBuilder<PropertyDescriptor?> { returnType = type; return this }
        override fun setModality(modality: Modality): CopyConfiguration { this.modality = modality; return this }
        override fun setVisibility(visibility: DescriptorVisibility): CopyConfiguration { this.visibility = visibility; return this }
        override fun setKind(kind: Kind): CopyConfiguration { this.kind = kind; return this }
        override fun setTypeParameters(parameters: List<TypeParameterDescriptor>): CallableMemberDescriptor.CopyBuilder<PropertyDescriptor?> { newTypeParameters = parameters; return this }
        override fun setDispatchReceiverParameter(dispatchReceiverParameter: ReceiverParameterDescriptor?): CopyConfiguration { this.dispatchReceiverParameter = dispatchReceiverParameter; return this }
        override fun setSubstitution(substitution: TypeSubstitution): CopyConfiguration { this.substitution = substitution; return this }
        override fun setCopyOverrides(copyOverrides: Boolean): CopyConfiguration { this.copyOverrides = copyOverrides; return this }
        override fun setName(name: Name): CallableMemberDescriptor.CopyBuilder<PropertyDescriptor?> { this.name = name; return this }
        override fun build(): PropertyDescriptor? = doSubstitute(this)
        internal open fun getOriginalGetter(): PropertyGetterDescriptor? = original?.getter
        internal open fun getOriginalSetter(): PropertySetterDescriptor? = original?.setter
    }
    override fun newCopyBuilder(): CopyConfiguration = CopyConfiguration()
    private fun getSourceToUseForCopy(preserveSource: Boolean, original: PropertyDescriptor?): SourceElement =
        if (preserveSource) (original ?: getOriginal()).getSource() else SourceElement.NO_SOURCE
    protected open fun doSubstitute(configuration: CopyConfiguration): PropertyDescriptor? {
        val substituted = createSubstitutedCopy(configuration.owner, configuration.modality, configuration.visibility, configuration.original,
            configuration.kind, configuration.name, getSourceToUseForCopy(configuration.preserveSourceElement, configuration.original))
        val originalTypeParameters = configuration.newTypeParameters ?: getTypeParameters()
        val substitutedTypeParameters = ArrayList<TypeParameterDescriptor>(originalTypeParameters.size)
        val substitutor = DescriptorSubstitutor.substituteTypeParameters(originalTypeParameters, configuration.substitution, substituted, substitutedTypeParameters)
        val originalOutType = configuration.returnType
        val outType = substitutor.substitute(originalOutType, Variance.OUT_VARIANCE) ?: return null
        val inType = substitutor.substitute(originalOutType, Variance.IN_VARIANCE)
        if (inType != null) substituted.setInType(inType)
        val dispatch = configuration.dispatchReceiverParameter
        val substitutedDispatch = if (dispatch != null) dispatch.substitute(substitutor) ?: return null else null
        val substitutedExtension = extensionReceiverParameter?.let { substituteParameterDescriptor(substitutor, substituted, it) }
        val substitutedContext = ArrayList<ReceiverParameterDescriptor>()
        for (receiver in contextReceiverParameters) {
            val replacement = substituteContextParameterDescriptor(substitutor, substituted, receiver)
            if (replacement != null) substitutedContext.add(replacement)
        }
        substituted.setType(outType, substitutedTypeParameters, substitutedDispatch, substitutedExtension, substitutedContext)
        val getter = storedGetter
        val newGetter = if (getter == null) null else PropertyGetterDescriptorImpl(substituted, getter.annotations, configuration.modality,
            normalizeVisibility(getter.getVisibility(), configuration.kind), getter.isDefault(), getter.isExternal(), getter.isInline(), configuration.kind,
            configuration.getOriginalGetter(), SourceElement.NO_SOURCE)
        if (newGetter != null) {
            val returnType = getter!!.getReturnType()
            newGetter.setInitialSignatureDescriptor(getSubstitutedInitialSignatureDescriptor(substitutor, getter))
            newGetter.initialize(if (returnType != null) substitutor.substitute(returnType, Variance.OUT_VARIANCE) else null)
        }
        val setter = storedSetter
        val newSetter = if (setter == null) null else PropertySetterDescriptorImpl(substituted, setter.annotations, configuration.modality,
            normalizeVisibility(setter.getVisibility(), configuration.kind), setter.isDefault(), setter.isExternal(), setter.isInline(), configuration.kind,
            configuration.getOriginalSetter(), SourceElement.NO_SOURCE)
        if (newSetter != null) {
            var substitutedParameters = FunctionDescriptorImpl.getSubstitutedValueParameters(newSetter, setter!!.getValueParameters(), substitutor, false, false, null)
            if (substitutedParameters == null) {
                substituted.setSetterProjectedOut(true)
                substitutedParameters = listOf(PropertySetterDescriptorImpl.createSetterParameter(newSetter, configuration.owner.builtIns.nothingType,
                    setter.getValueParameters()[0].annotations))
            }
            if (substitutedParameters.size != 1) throw IllegalStateException()
            newSetter.setInitialSignatureDescriptor(getSubstitutedInitialSignatureDescriptor(substitutor, setter))
            newSetter.initialize(substitutedParameters[0])
        }
        substituted.initialize(newGetter, newSetter, backingField?.let { FieldDescriptorImpl(it.annotations, substituted) },
            delegateField?.let { FieldDescriptorImpl(it.annotations, substituted) })
        if (configuration.copyOverrides) {
            val overridden = SmartSet.create<CallableMemberDescriptor?>()
            for (property in getOverriddenDescriptors()) overridden.add(property.substitute(substitutor))
            @Suppress("UNCHECKED_CAST")
            substituted.setOverriddenDescriptors(overridden as Collection<CallableMemberDescriptor>)
        }
        if (isConst() && compileTimeInitializerFactory != null) substituted.setCompileTimeInitializer(compileTimeInitializer, compileTimeInitializerFactory!!)
        return substituted
    }
    protected open fun createSubstitutedCopy(newOwner: DeclarationDescriptor, newModality: Modality, newVisibility: DescriptorVisibility,
        original: PropertyDescriptor?, kind: Kind, newName: Name, source: SourceElement): PropertyDescriptorImpl =
        PropertyDescriptorImpl(newOwner, original, annotations, newModality, newVisibility, isVar(), newName, kind, source,
            isLateInit(), isConst(), isExpect(), isActual(), isExternal(), isDelegated)
    override fun <R, D> accept(visitor: DeclarationDescriptorVisitor<R, D>?, data: D): R = visitor!!.visitPropertyDescriptor(this, data)
    override fun getOriginal(): PropertyDescriptor = if (original === this) this else original.getOriginal()
    override fun getKind(): Kind = kind
    override fun isExpect(): Boolean = isExpect
    override fun isActual(): Boolean = isActual
    override fun getBackingField(): FieldDescriptor? = backingField
    override fun getDelegateField(): FieldDescriptor? = delegateField
    @Suppress("UNCHECKED_CAST")
    override fun setOverriddenDescriptors(overriddenDescriptors: Collection<CallableMemberDescriptor>) { overriddenProperties = overriddenDescriptors as Collection<PropertyDescriptor?> }
    @Suppress("UNCHECKED_CAST")
    override fun getOverriddenDescriptors(): Collection<PropertyDescriptor> = (overriddenProperties ?: emptyList()) as Collection<PropertyDescriptor>
    override fun copy(newOwner: DeclarationDescriptor?, modality: Modality?, visibility: DescriptorVisibility?, kind: Kind?, copyOverrides: Boolean): PropertyDescriptor =
        newCopyBuilder().setOwner(newOwner!!).setOriginal(null).setModality(modality!!).setVisibility(visibility!!).setKind(kind!!).setCopyOverrides(copyOverrides).build()!!
    override fun <V> getUserData(key: UserDataKey<V>?): V? = null
    companion object {
        @kotlin.jvm.JvmStatic
        fun create(containingDeclaration: DeclarationDescriptor, annotations: Annotations, modality: Modality, visibility: DescriptorVisibility,
            isVar: Boolean, name: Name, kind: Kind, source: SourceElement, lateInit: Boolean, isConst: Boolean, isExpect: Boolean,
            isActual: Boolean, isExternal: Boolean, isDelegated: Boolean): PropertyDescriptorImpl =
            PropertyDescriptorImpl(containingDeclaration, null, annotations, modality, visibility, isVar, name, kind, source, lateInit, isConst,
                isExpect, isActual, isExternal, isDelegated)
        private fun normalizeVisibility(previous: DescriptorVisibility, kind: Kind): DescriptorVisibility =
            if (kind == Kind.FAKE_OVERRIDE && DescriptorVisibilities.isPrivate(previous.normalize())) DescriptorVisibilities.INVISIBLE_FAKE else previous
        private fun substituteParameterDescriptor(substitutor: TypeSubstitutor, property: PropertyDescriptor, receiver: ReceiverParameterDescriptor): ReceiverParameterDescriptor? {
            val type = substitutor.substitute(receiver.getType(), Variance.IN_VARIANCE) ?: return null
            return ReceiverParameterDescriptorImpl(property, ExtensionReceiver(property, type, receiver.getValue()), receiver.annotations)
        }
        private fun substituteContextParameterDescriptor(substitutor: TypeSubstitutor, property: PropertyDescriptor, receiver: ReceiverParameterDescriptor): ReceiverParameterDescriptor? {
            val type = substitutor.substitute(receiver.getType(), Variance.IN_VARIANCE) ?: return null
            return ReceiverParameterDescriptorImpl(property, ContextReceiver(property, type,
                (receiver.getValue() as ImplicitContextReceiver).customLabelName, receiver.getValue()), receiver.annotations)
        }
        private fun getSubstitutedInitialSignatureDescriptor(substitutor: TypeSubstitutor, accessor: PropertyAccessorDescriptor): FunctionDescriptor? =
            accessor.getInitialSignatureDescriptor()?.substitute(substitutor)
    }
}
