#!/usr/bin/env python3
"""Build pinned, unmodified single-thread wasi-libc with native TLS preserved."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile

HERE = Path(__file__).resolve().parent
FLAGS = '-matomics -mbulk-memory -ftls-model=local-exec'


def identity(file):
    path = Path(file)
    with path.open('rb') as stream:
        return {'bytes': path.stat().st_size, 'sha256': hashlib.file_digest(stream, 'sha256').hexdigest()}


def extract_source(archive, destination, commit):
    prefix = 'wasi-libc-' + commit
    destination.mkdir()
    with tarfile.open(archive) as packed:
        for member in packed:
            name = Path(member.name)
            if name.is_absolute() or '..' in name.parts or not name.parts or name.parts[0] != prefix:
                raise RuntimeError('Unsafe or unexpected wasi-libc archive path')
            target = destination / name
            if destination not in target.resolve().parents:
                raise RuntimeError('Source archive escapes its output')
            if member.isdir():
                target.mkdir(parents=True, exist_ok=True)
            elif member.isfile():
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(packed.extractfile(member).read())
                target.chmod(member.mode & 0o755)
            elif member.issym():
                if destination not in (target.parent / member.linkname).resolve().parents:
                    raise RuntimeError('Unsafe source archive symbolic link')
                target.parent.mkdir(parents=True, exist_ok=True)
                target.symlink_to(member.linkname)
            else:
                raise RuntimeError('Unexpected source archive entry type')
    return destination / prefix


def check_configuration(cache, commands):
    values = {}
    for line in cache.splitlines():
        if line and not line.startswith(('#', '//')) and ':' in line and '=' in line:
            key, value = line.split('=', 1)
            values[key.split(':', 1)[0]] = value
    required = {'TARGET_TRIPLE': 'wasm32-wasip1', 'CMAKE_C_FLAGS': FLAGS,
                'MALLOC': 'dlmalloc', 'BUILD_SHARED': 'OFF', 'BUILD_TESTS': 'OFF',
                'SETJMP': 'OFF', 'SIMD': 'OFF', 'LTO': '', 'BINDINGS_TARGET': 'OFF'}
    for key, value in required.items():
        if values.get(key) != value:
            raise RuntimeError('Incorrect private TLS libc configuration: ' + key)
    if not commands:
        raise RuntimeError('No actual libc compilation commands')
    for command in commands:
        text = command['command']
        for flag in ['-matomics', '-mbulk-memory', '-ftls-model=local-exec', '-mthread-model single']:
            if flag not in text:
                raise RuntimeError('Private libc compilation lost TLS flags: ' + flag)
        if any(flag in text for flag in ['-pthread', '-D_REENTRANT', '-mthread-model posix']):
            raise RuntimeError('Private TLS libc enabled pthread configuration')
        if '/wasi-threads/' in command['file']:
            raise RuntimeError('Private TLS libc selected threaded implementation sources')
    return required


def check_source_inventory(original, current):
    for name, value in original.items():
        if current.get(name) != value:
            raise RuntimeError('Upstream libc source changed: ' + name)
    # configure_file writes these exact files. The pinned archive can already
    # contain their identical generated bytes, in which case there is no new path.
    generated = {'wasi/p2/wit/wasi-libc.wit', 'wasi/p3/wit/wasi-libc.wit'} - set(original)
    extras = set(current) - set(original)
    if extras != generated:
        raise RuntimeError('Unexpected generated libc source paths: ' + str(sorted(extras)))
    return {name: current[name] for name in sorted(extras)}


def build(work, sdk, archive, output, jobs, node):
    if jobs < 1 or jobs > 4:
        raise ValueError('Use one to four bounded libc build jobs')
    if output == sdk or sdk in output.parents or output == work / 'gcc' or work / 'gcc' in output.parents:
        raise ValueError('Private libc output must not overlap source or SDK')
    output.mkdir(parents=True, exist_ok=False)
    for name in ['logs', 'tmp', 'licenses']:
        (output / name).mkdir()
    frozen = {}
    report = {'schemaVersion': 1, 'kind': 'gcc-wasi-private-tls-libc-build',
              'status': 'running', 'commands': [], 'jobs': jobs}

    def save():
        (output / 'build.json').write_text(json.dumps(report, indent=2) + '\n')

    def record(file):
        return {'path': str(Path(file).resolve()), **identity(file)}

    def freeze(file):
        item = record(file)
        expected = {key: item[key] for key in ['bytes', 'sha256']}
        if frozen.setdefault(item['path'], expected) != expected:
            raise RuntimeError('Changed private TLS libc input')
        return item

    environment = dict(os.environ, LC_ALL='C', TMPDIR=str(output / 'tmp'))
    for name in ['CFLAGS', 'CXXFLAGS', 'CPPFLAGS', 'LDFLAGS', 'LIBS', 'CC', 'CXX', 'CPATH',
                 'C_INCLUDE_PATH', 'CPLUS_INCLUDE_PATH', 'LIBRARY_PATH']:
        environment.pop(name, None)

    def run(argv, label, timeout=120):
        argv = list(map(str, argv)); stdout, stderr = [output / 'logs' / (label + '.' + kind) for kind in ['stdout', 'stderr']]
        entry = {'argv': argv, 'cwd': str(output), 'timeoutSeconds': timeout}; report['commands'].append(entry)
        with stdout.open('xb') as out, stderr.open('xb') as err:
            try:
                result = subprocess.run(argv, cwd=output, env=environment, stdout=out, stderr=err, timeout=timeout)
                entry['status'] = result.returncode
            except (OSError, subprocess.TimeoutExpired) as error:
                entry.update(status=None, error=str(error))
        entry.update(stdout=record(stdout), stderr=record(stderr)); save()
        if entry.get('status') != 0:
            raise RuntimeError(f'Private TLS libc {label} failed; status={entry.get("status")}; stderr={stderr}')
        return entry

    try:
        report['recipe'] = freeze(Path(__file__))
        report['runtimeLock'] = freeze(HERE / 'runtime.lock.json')
        lock = json.loads((HERE / 'runtime.lock.json').read_text())['wasiLibc']
        report['sourceArchive'] = freeze(archive)
        if report['sourceArchive']['sha256'] != lock['sourceArchiveSha256']:
            raise RuntimeError('Private libc source archive is not locked')
        report['commit'] = lock['commit']
        report['tools'] = {name: freeze(file) for name, file in {
            'clang': sdk / 'bin/clang', 'ar': sdk / 'bin/llvm-ar', 'ranlib': sdk / 'bin/llvm-ranlib',
            'nm': sdk / 'bin/llvm-nm', 'objdump': work / 'wabt-native/wasm-objdump',
            'cmake': shutil.which('cmake'), 'ninja': shutil.which('ninja'), 'node': node,
            'python': sys.executable}.items()}
        builtins = sdk / 'lib/clang/22/lib/wasm32-unknown-wasi/libclang_rt.builtins.a'
        report['builtins'] = freeze(builtins)
        report['clangHeaders'] = [freeze(file) for file in sorted((sdk / 'lib/clang/22/include').rglob('*')) if file.is_file()]
        sdk_archive = sdk.parent / (sdk.name + '.tar.gz')
        report['sdkArchive'] = freeze(sdk_archive)
        if report['sdkArchive']['sha256'] != lock['sdkArchiveSha256']:
            raise RuntimeError('SDK compiler archive is not locked')
        pinned = [report['tools'][name] for name in ['clang', 'ar', 'ranlib', 'nm']]
        pinned += [report['builtins'], *report['clangHeaders']]
        expected_members = {sdk.name + '/' + Path(item['path']).relative_to(sdk).as_posix():
                            {key: item[key] for key in ['bytes', 'sha256']} for item in pinned}
        remaining = set(expected_members)
        with tarfile.open(sdk_archive) as packed:
            for member in packed:
                if member.name not in expected_members:
                    continue
                if not member.isfile():
                    raise RuntimeError('Unexpected SDK compiler input entry')
                data = packed.extractfile(member).read()
                if {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()} != expected_members[member.name]:
                    raise RuntimeError('SDK compiler/header differs from the original archive: ' + member.name)
                remaining.remove(member.name)
        if remaining:
            raise RuntimeError('SDK compiler inputs are not in the original archive')
        report['inspectors'] = [freeze(HERE / name) for name in ['tls-inspect.mjs', 'symbol-alias-inspect.mjs']]
        source = extract_source(archive, output / 'source', lock['commit'])
        source_inputs = {str(file.relative_to(source)): identity(file) for file in sorted(source.rglob('*')) if file.is_file()}
        configuration = output / 'configuration'
        run([report['tools']['cmake']['path'], '-S', source, '-B', configuration, '-G', 'Ninja',
             '-DCMAKE_C_COMPILER=' + str(sdk / 'bin/clang'), '-DCMAKE_ASM_COMPILER=' + str(sdk / 'bin/clang'),
             '-DCMAKE_AR=' + str(sdk / 'bin/llvm-ar'), '-DCMAKE_RANLIB=' + str(sdk / 'bin/llvm-ranlib'),
             '-DCMAKE_NM=' + str(sdk / 'bin/llvm-nm'), '-DCMAKE_C_COMPILER_TARGET=wasm32-wasip1',
             '-DCMAKE_TRY_COMPILE_TARGET_TYPE=STATIC_LIBRARY', '-DCMAKE_C_FLAGS=' + FLAGS,
             '-DTARGET_TRIPLE=wasm32-wasip1', '-DMALLOC=dlmalloc', '-DBUILD_SHARED=OFF',
             '-DBUILD_TESTS=OFF', '-DSETJMP=OFF', '-DSIMD=OFF', '-DCHECK_SYMBOLS=OFF', '-DLTO=',
             '-DBINDINGS_TARGET=OFF', '-DBUILTINS_LIB=' + str(builtins),
             '-DCMAKE_EXPORT_COMPILE_COMMANDS=ON'], 'configure')
        commands = json.loads((configuration / 'compile_commands.json').read_text())
        # The CMake project describes excluded shared targets as well. Freeze
        # and validate the actual static sources selected by the requested target.
        static_commands = [item for item in commands if '-static.dir/' in item['command']]
        report['configurationChecks'] = check_configuration((configuration / 'CMakeCache.txt').read_text(), static_commands)
        run([report['tools']['cmake']['path'], '--build', configuration, '--target', 'sysroot-c-static', 'sysroot-c-printscan-long-double',
             '--parallel', str(jobs)], 'build', 1800)
        objects = sorted(configuration.rglob('*.obj'))
        if not objects:
            raise RuntimeError('No compiled private TLS libc objects')
        report['objects'] = []
        forbidden = ['memory.atomic.wait32', 'memory.atomic.wait64', 'memory.atomic.notify']
        for index, obj in enumerate(objects):
            inspected = run([work / 'wabt-native/wasm-objdump', '-d', obj], f'object-{index:04d}')
            text = Path(inspected['stdout']['path']).read_text()
            if any(op in text for op in forbidden):
                raise RuntimeError('Private libc contains a shared-memory wait/notify instruction: ' + str(obj))
            report['objects'].append({'object': record(obj), 'disassembly': inspected['stdout']})
        candidates = [file for file in objects if file.as_posix().endswith((
            '/cloudlibc/src/libc/errno/errno.c.obj', '/sources/__errno_location.c.obj', '/musl/src/internal/intscan.c.obj'))]
        if len(candidates) != 3:
            raise RuntimeError('Expected the actual errno definition, accessor and integer scanner objects')
        formatters = [file for file in objects if '/printscan-longdouble-static.dir/' in file.as_posix()]
        if sorted(file.name for file in formatters) != sorted(['floatscan.c.obj', 'strtod.c.obj', 'vfprintf.c.obj', 'vfwprintf.c.obj', 'vfscanf.c.obj', 'wcstod.c.obj']):
            raise RuntimeError('Actual private TLS long-double formatter objects are missing')
        direct_formatters = [file for file in formatters if file.name in ['floatscan.c.obj', 'vfprintf.c.obj', 'vfwprintf.c.obj']]
        report['formatterDelegation'] = []
        for file in formatters:
            if file in direct_formatters:
                continue
            inspected = run([sdk / 'bin/llvm-nm', '--format=posix', file], file.name + '-symbols')
            symbols = Path(inspected['stdout']['path']).read_text()
            if not any(line.split()[:2] == ['__floatscan', 'U'] for line in symbols.splitlines()):
                raise RuntimeError('Long-double scanner does not call the real TLS-aware floatscan')
            report['formatterDelegation'].append({'object': record(file), 'symbols': inspected['stdout'], 'callee': '__floatscan'})
        script = output / 'inspect-tls.mjs'
        script.write_text('import{readFile}from"node:fs/promises";import{inspectTlsObject}from'
            + json.dumps((HERE / 'tls-inspect.mjs').as_uri())
            + ';const r=[];for(const file of process.argv.slice(2)){const i=inspectTlsObject(await readFile(file));'
            + 'if(!i.hasTls||!i.tlsSymbols.some(s=>s.name==="errno"))throw Error("Actual errno TLS metadata is absent: "+file);'
            + 'r.push({file,tlsSymbols:i.tlsSymbols,tlsRelocations:i.tlsRelocations});}console.log(JSON.stringify(r));\n')
        inspected = run([node, script, *candidates, *direct_formatters], 'tls-metadata')
        report['tlsInspection'] = json.loads(Path(inspected['stdout']['path']).read_text())
        report['libraries'], report['memberInventories'] = {}, {}
        for name in ['libc.a', 'libc-printscan-long-double.a']:
            library = configuration / 'sysroot/lib/wasm32-wasip1' / name
            destination = output / 'sysroot/lib/wasm32-wasi-tls' / name
            destination.parent.mkdir(parents=True, exist_ok=True); shutil.copyfile(library, destination)
            report['libraries'][name] = record(destination)
            listing = run([sdk / 'bin/llvm-ar', 't', library], name + '-members')
            report['memberInventories'][name] = Path(listing['stdout']['path']).read_text().splitlines()
        report['library'] = report['libraries']['libc.a']
        report['members'] = report['memberInventories']['libc.a']
        if sum(map(len, report['memberInventories'].values())) != len(objects):
            raise RuntimeError('Archive member inventory differs from actual built objects')
        generated = {str(file.relative_to(source)): identity(file) for file in source.rglob('*') if file.is_file()}
        report['sourceInputs'] = source_inputs
        report['generatedSources'] = check_source_inventory(source_inputs, generated)
        report['configuration'] = {name: record(configuration / name) for name in ['CMakeCache.txt', 'compile_commands.json', 'build.ninja']}
        report['licenses'] = []
        for name in ['LICENSE', 'LICENSE-APACHE', 'LICENSE-APACHE-LLVM', 'LICENSE-MIT',
                     'libc-top-half/musl/COPYRIGHT', 'dlmalloc/COPYING']:
            origin = source / name
            if not origin.is_file():
                continue
            target = output / 'licenses' / name.replace('/', '-')
            shutil.copyfile(origin, target); report['licenses'].append({'source': record(origin), 'installed': record(target)})
        report['profile'] = {'target': 'wasm32-wasip1', 'threads': False, 'reentrant': False,
            'compilerThreadModel': 'single', 'nativeTls': True, 'allocator': 'unmodified-single-thread-dlmalloc',
            'atomicWaitNotify': False, 'sourceModified': False, 'longDoubleFormatting': True, 'executionQualified': False}
        report['inputs'] = [{'path': name, **value} for name, value in sorted(frozen.items())]
        report['inputsUnchanged'] = all(identity(name) == value for name, value in frozen.items())
        if not report['inputsUnchanged']:
            raise RuntimeError('Private TLS libc build inputs changed')
        report['status'] = 'built-unverified'; save()
    except Exception as error:
        report.update(status='failed', error=str(error)); save(); raise


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ['work', 'sdk', 'source-archive', 'output']:
        parser.add_argument('--' + name, required=True, type=Path)
    parser.add_argument('--node', default='node')
    parser.add_argument('--jobs', type=int, default=2)
    args = parser.parse_args()
    build(*(getattr(args, name).resolve() for name in ['work', 'sdk', 'source_archive', 'output']),
          args.jobs, Path(shutil.which(args.node) or args.node).resolve())
